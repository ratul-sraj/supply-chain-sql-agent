"""Evaluation harness for the supply-chain text-to-SQL agent.

Runs every question in eval/questions.jsonl through the agent, compares the
agent's result set against the gold result set (order-insensitive unless the
gold query is ordered), and writes:

    eval/results.json   machine-readable metrics + per-question detail
    eval/report.md      human-readable summary with per-question failures

Metrics
-------
execution_accuracy : fraction of questions whose result set matches gold
valid_sql_rate     : fraction where the agent produced a runnable SQL statement
repair_rate        : fraction of questions that triggered >=1 self-repair round
mean_latency_ms    : average end-to-end agent latency

Usage:
    python eval/run_eval.py --planner template
    python eval/run_eval.py --planner llm        # needs OPENAI_API_KEY
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from sql_agent.db import SafeDB               # noqa: E402
from sql_agent.agent import SQLAgent, build_planner  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
QUESTIONS = os.path.join(HERE, "questions.jsonl")
RESULTS = os.path.join(HERE, "results.json")
REPORT = os.path.join(HERE, "report.md")


def canonical_hash(rows: list[dict], ordered: bool) -> str:
    vals = [tuple(r.values()) for r in rows]
    if not ordered:
        vals = sorted(vals, key=lambda t: [str(x) for x in t])
    return hashlib.sha256(json.dumps(vals, default=str).encode()).hexdigest()[:16]


def load_questions(path: str | None = None) -> list[dict]:
    with open(path or QUESTIONS, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def run(planner_name: str, questions_path: str | None = None) -> dict:
    db = SafeDB()
    agent = SQLAgent(db=db, planner=build_planner(planner_name))
    questions = load_questions(questions_path)

    per_q = []
    n_match = n_valid = n_repaired = 0
    total_latency = 0.0

    for q in questions:
        res = agent.ask(q["question"])
        got_hash = canonical_hash(res.rows, q["ordered"]) if res.error is None else None
        matched = (res.error is None and got_hash == q["expected_hash"]
                   and res.row_count == q["expected_row_count"])
        valid = res.sql is not None and res.error is None
        if matched:
            n_match += 1
        if valid:
            n_valid += 1
        if res.repaired:
            n_repaired += 1
        total_latency += res.latency_ms
        per_q.append({
            "id": q["id"],
            "question": q["question"],
            "gold_sql": q["gold_sql"],
            "agent_sql": res.sql,
            "expected_hash": q["expected_hash"],
            "got_hash": got_hash,
            "expected_row_count": q["expected_row_count"],
            "got_row_count": res.row_count,
            "matched": matched,
            "valid_sql": valid,
            "repaired": res.repaired,
            "error": res.error,
            "latency_ms": res.latency_ms,
            "steps": len(res.steps),
        })

    n = len(questions)
    return {
        "planner": planner_name,
        "total": n,
        "execution_accuracy": round(n_match / n, 4),
        "valid_sql_rate": round(n_valid / n, 4),
        "repair_rate": round(n_repaired / n, 4),
        "mean_latency_ms": round(total_latency / n, 3),
        "correct": n_match,
        "valid": n_valid,
        "repaired": n_repaired,
        "per_question": per_q,
    }


def write_report(metrics: dict, report_path: str | None = None) -> None:
    failures = [r for r in metrics["per_question"] if not r["matched"]]
    lines = [
        "# Evaluation report — supply-chain text-to-SQL agent",
        "",
        f"**Planner:** `{metrics['planner']}`  |  "
        f"**Questions:** {metrics['total']}  |  "
        f"Generated by `eval/run_eval.py` (results are measured, not estimated).",
        "",
        "## Summary metrics",
        "",
        "| Metric | Value |",
        "| --- | --- |",
        f"| Execution accuracy (result-set match) | **{metrics['execution_accuracy']*100:.1f}%** "
        f"({metrics['correct']}/{metrics['total']}) |",
        f"| Valid-SQL rate | {metrics['valid_sql_rate']*100:.1f}% "
        f"({metrics['valid']}/{metrics['total']}) |",
        f"| Self-repair rate | {metrics['repair_rate']*100:.1f}% "
        f"({metrics['repaired']}/{metrics['total']}) |",
        f"| Mean latency | {metrics['mean_latency_ms']:.1f} ms |",
        "",
        "## Per-question failures",
        "",
    ]
    if not failures:
        lines.append("_None — every question matched its gold result set._")
    else:
        lines.append("| # | Question | Expected rows | Got rows | Error |")
        lines.append("| --- | --- | --- | --- | --- |")
        for f in failures:
            err = (f["error"] or "result mismatch").replace("|", "\\|")
            lines.append(f"| {f['id']} | {f['question']} | "
                         f"{f['expected_row_count']} | {f['got_row_count']} | {err} |")
    lines += [
        "",
        "## How to reproduce",
        "",
        "```bash",
        "python scripts/build_db.py",
        "python eval/run_eval.py --planner template",
        "```",
        "",
    ]
    with open(report_path or REPORT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--planner", choices=["auto", "llm", "template"], default="template")
    ap.add_argument("--quiet", action="store_true")
    ap.add_argument("--questions", default=QUESTIONS,
                    help="question set (default: eval/questions.jsonl)")
    ap.add_argument("--results", default=RESULTS,
                    help="metrics output path (default: eval/results.json)")
    ap.add_argument("--report", default=REPORT,
                    help="markdown report path (default: eval/report.md)")
    a = ap.parse_args()

    t0 = time.monotonic()
    metrics = run(a.planner, a.questions)
    metrics["wall_seconds"] = round(time.monotonic() - t0, 2)

    with open(a.results, "w", encoding="utf-8") as f:
        json.dump(metrics, f, indent=2, ensure_ascii=False)
    write_report(metrics, a.report)

    if not a.quiet:
        print(json.dumps({k: v for k, v in metrics.items() if k != "per_question"}, indent=2))
    print(f"\nWrote {RESULTS}\nWrote {REPORT}")


if __name__ == "__main__":
    main()
